def _p(doc: Document, text: str, bold: bool = False, size: int | None = None) -> None:
    r = doc.add_paragraph().add_run(text)
    r.bold = bold
    if size:
        r.font.size = Pt(size)


def _h(doc: Document, text: str, level: int = 1) -> None:
    doc.add_heading(text, level=level)


def _fig(doc: Document, image_path: Path, caption: str, width_cm: float = 14.0) -> None:
    if not image_path.is_file():
        _p(doc, f"[Отсутствует файл рисунка: {image_path.name}]", bold=True)
    else:
        doc.add_picture(str(image_path), width=Cm(width_cm))
    cap = doc.add_paragraph(caption)
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for run in cap.runs:
        run.italic = True
        run.font.size = Pt(11)


